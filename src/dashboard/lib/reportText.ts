// Shared text helpers for the PDF and Markdown report exports.

export const REPORT_FOOTER = 'Generated by Vouch · vouch.so';

// jsPDF's built-in Helvetica only covers WinAnsi (Windows-1252). A single character outside it
// makes jsPDF encode the whole line as 2-byte text, which renders as gibberish.
const WINANSI_EXTRAS = new Set('€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ');
const isWinAnsi = (ch: string) => {
  const code = ch.charCodeAt(0);
  return ch.length === 1 && (code === 9 || code === 10 || code === 13 || (code >= 0x20 && code <= 0x7e) || (code >= 0xa0 && code <= 0xff) || WINANSI_EXTRAS.has(ch));
};

// Common characters with a close WinAnsi equivalent (or none, for invisible ones).
const REPLACEMENTS: Record<string, string> = {
  '\u2212': '-', '\u2010': '-', '\u2011': '-', '\u2012': '-', '\u2015': '—',
  '\u2032': "'", '\u2033': '"', '\u2248': '~', '\u2264': '<=', '\u2265': '>=', '\u2192': '->', '\u2190': '<-',
  '\u2009': ' ', '\u200a': ' ', '\u202f': ' ', '\u2007': ' ', '\u2008': ' ',
  '\u200b': '', '\u2060': '', '\ufeff': '',
  'ł': 'l', 'Ł': 'L', 'đ': 'd', 'Đ': 'D', 'ı': 'i', 'ħ': 'h', 'Ħ': 'H',
};

// Emoji and the invisible pieces that build them (joiners, variation selectors, skin tones, flags, keycaps, tags).
const EMOJI = /\p{Extended_Pictographic}|\p{Emoji_Modifier}|\u200d|\ufe0e|\ufe0f|\u20e3|[\u{1F1E6}-\u{1F1FF}]|[\u{E0020}-\u{E007F}]/u;

/** Makes a string safe for jsPDF's built-in fonts: maps look-alikes, drops emoji, and uses '?' for anything else it can't show. */
export function toPdfText(text: string): string {
  let out = '';
  for (const ch of text.normalize('NFC')) {
    if (isWinAnsi(ch)) out += ch;
    else if (ch in REPLACEMENTS) out += REPLACEMENTS[ch];
    else if (EMOJI.test(ch)) continue;
    else {
      // Accented letters outside WinAnsi (e.g. Polish ś, Turkish ğ) fall back to the base letter.
      const base = ch.normalize('NFKD').replace(/\p{M}/gu, '');
      out += base && [...base].every(isWinAnsi) ? base : /\p{M}/u.test(ch) ? '' : '?';
    }
  }
  return out;
}

/** A percentage, or '—' when it isn't known. */
export const formatRate = (rate: number | null | undefined, digits: number): string =>
  rate == null ? '—' : `${rate.toFixed(digits)}%`;

/** Keeps a value inside one Markdown table cell. */
export function mdCell(value: string | null | undefined): string {
  return (value ?? '').replace(/\|/g, '\\|').replace(/\s*[\r\n]+\s*/g, ' ').trim();
}
